// MUSIQUE : UN SEUL GESTIONNAIRE
// ========================================

(() => {
  const musicToggle = document.getElementById("musicToggle");
  const audio = document.getElementById("backgroundMusic");

  if (!musicToggle || !audio) {
    console.warn(
      "EBOU : bouton musique ou élément audio introuvable."
    );
    return;
  }

  audio.loop = true;
  audio.volume = 0.25;

  function updateMusicButton() {
    const isPlaying = !audio.paused;
    const lang = document.documentElement.lang || "fr";
    const dict = translations[lang] || translations.fr;
    const label = isPlaying ? dict.musicOn : dict.musicOff;

    musicToggle.setAttribute("aria-pressed", String(isPlaying));
    musicToggle.setAttribute("aria-label", label);
    musicToggle.setAttribute("title", label);

    const textElement = musicToggle.querySelector("[data-music-label]");

    if (textElement) {
      textElement.textContent = label;
    }
  }

  musicToggle.addEventListener("click", async () => {
    if (!audio.paused) {
      audio.pause();
      updateMusicButton();
      return;
    }

    try {
      await audio.play();
      updateMusicButton();
    } catch (error) {
      console.error(
        "EBOU : lecture audio impossible. Vérifie le chemin du fichier audio.",
        error
      );

      updateMusicButton();

      alert(
        "La musique ne peut pas être lue. Vérifie que le fichier audio existe et que son format est compatible."
      );
    }
  });

  audio.addEventListener("play", updateMusicButton);
  audio.addEventListener("pause", updateMusicButton);
  audio.addEventListener("ended", updateMusicButton);

  updateMusicButton();
})();
