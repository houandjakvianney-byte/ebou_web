(() => {
  const banner = document.getElementById("cookieBanner");

  if (!banner) return;

  const acceptButton = document.getElementById("cookieAccept");
  const dismissButton = document.getElementById("cookieDismiss");
  const laterButton = document.getElementById("cookieClose");

  // Uniquement la préférence d'affichage de la bannière.
  const storageKey = "ebou_cookie_notice_choice";

  const hideBanner = () => {
    banner.hidden = true;
  };

  const saveChoice = (choice) => {
    try {
      localStorage.setItem(storageKey, choice);
    } catch (error) {
      // Si le stockage est indisponible, la bannière
      // est quand même masquée pour cette visite.
    }

    hideBanner();
  };

  let savedChoice = null;

  try {
    savedChoice = localStorage.getItem(storageKey);
  } catch (error) {
    // Le stockage peut être désactivé par le navigateur.
  }

  if (!savedChoice) {
    banner.hidden = false;
  }

  // « Compris » : le visiteur a pris connaissance du message.
  acceptButton?.addEventListener("click", () => {
    saveChoice("accepted");
  });

  // Croix et « Plus tard » : le visiteur ferme la bannière.
  // Ce choix est mémorisé pour ne pas la réafficher au prochain chargement.
  dismissButton?.addEventListener("click", () => {
    saveChoice("dismissed");
  });

  laterButton?.addEventListener("click", () => {
    saveChoice("dismissed");
  });
})();

