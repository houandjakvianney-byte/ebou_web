// CARROUSEL DES ÉTAPES SUR MOBILE
// ========================================

(() => {
  const track = document.getElementById("stepsTrack");
  const pagination = document.getElementById("stepsPagination");

  if (!track || !pagination) return;

  const cards = Array.from(track.querySelectorAll(".step-card"));
  const dots = Array.from(pagination.querySelectorAll(".steps-dot"));

  if (!cards.length || cards.length !== dots.length) return;

  const mobileQuery = window.matchMedia("(max-width: 780px)");
  let scrollFrame = null;

  function setActiveSlide(index) {
    dots.forEach((dot, i) => {
      const active = i === index;

      dot.classList.toggle("is-active", active);

      if (active) {
        dot.setAttribute("aria-current", "step");
      } else {
        dot.removeAttribute("aria-current");
      }
    });
  }

  function getCurrentSlide() {
    const trackRect = track.getBoundingClientRect();
    let closestIndex = 0;
    let smallestDistance = Infinity;

    cards.forEach((card, index) => {
      const distance = Math.abs(
        card.getBoundingClientRect().left - trackRect.left
      );

      if (distance < smallestDistance) {
        smallestDistance = distance;
        closestIndex = index;
      }
    });

    return closestIndex;
  }

  function goToSlide(index) {
    if (!mobileQuery.matches) return;

    const card = cards[index];
    if (!card) return;

    track.scrollTo({
      left: card.offsetLeft - cards[0].offsetLeft,
      behavior: window.matchMedia(
        "(prefers-reduced-motion: reduce)"
      ).matches ? "auto" : "smooth"
    });

    setActiveSlide(index);
  }

  dots.forEach((dot, index) => {
    dot.addEventListener("click", () => goToSlide(index));
  });

  track.addEventListener("scroll", () => {
    if (!mobileQuery.matches) return;

    if (scrollFrame !== null) {
      cancelAnimationFrame(scrollFrame);
    }

    scrollFrame = requestAnimationFrame(() => {
      setActiveSlide(getCurrentSlide());
      scrollFrame = null;
    });
  }, { passive: true });

  function updateLayout() {
    if (mobileQuery.matches) {
      setActiveSlide(getCurrentSlide());
    } else {
      track.scrollLeft = 0;
      setActiveSlide(0);
    }
  }

  if (mobileQuery.addEventListener) {
    mobileQuery.addEventListener("change", updateLayout);
  } else {
    mobileQuery.addListener(updateLayout);
  }

  updateLayout();
})();

