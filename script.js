(() => {
  const actions = document.getElementById("floatingActions");
  if (!actions) return;

  let ticking = false;

  function updateFloatingActions() {
    actions.classList.toggle("is-visible", window.scrollY > 30);
    ticking = false;
  }

  window.addEventListener("scroll", () => {
    if (ticking) return;

    ticking = true;
    window.requestAnimationFrame(updateFloatingActions);
  }, { passive: true });

  updateFloatingActions();
})();

/* ==========================================
   EBOU — MAGIC LOGO CONSTRUCTION
========================================== */

(() => {
  const loader = document.getElementById("ebou-magic-loader");
  if (!loader) return;

  const logo = document.getElementById("magicLogo");
  const logoShell = document.getElementById("magicLogoShell");
  const mascot = document.getElementById("magicMascot");
  const energy = loader.querySelector(".magic-energy");
  const progressBar = document.getElementById("magicProgressFill");
  const progressTrack = document.getElementById("magicProgress");
  const percentLabel = document.getElementById("magicPercent");
  const statusLabel = document.getElementById("magicStatus");
  const captionLabel = document.getElementById("magicCaption");
  const sparks = loader.querySelectorAll(".magic-spark");

  let progress = 0;
  let pageReady = document.readyState === "complete";
  let finished = false;
  let animationFrame = null;
  let lastTime = 0;

  const stages = [
    { at: 0, text: "Préparation de la magie…", caption: "Tout commence par une idée." },
    { at: 18, text: "Invocation du logo…", caption: "Les premiers éléments apparaissent." },
    { at: 42, text: "Assemblage des couleurs…", caption: "Le vert, le blanc et le rouge prennent vie." },
    { at: 65, text: "Le logo prend forme…", caption: "Chaque détail retrouve sa place." },
    { at: 84, text: "Presque prêt…", caption: "La magie touche à sa fin." },
    { at: 100, text: "Bienvenue sur EBOU !", caption: "Ensemble, retrouvons ce qui compte." }
  ];

  function setProgress(value) {
    progress = Math.max(0, Math.min(100, value));

    if (progressBar) {
      progressBar.style.width = `${progress}%`;
    }

    if (percentLabel) {
      percentLabel.textContent = `${Math.floor(progress)}%`;
    }

    if (progressTrack) {
      progressTrack.setAttribute("aria-valuenow", String(Math.floor(progress)));
    }

    const stage = [...stages].reverse().find(item => progress >= item.at);

    if (stage) {
      if (statusLabel) statusLabel.textContent = stage.text;
      if (captionLabel) captionLabel.textContent = stage.caption;
    }

    if (progress >= 18) loader.classList.add("magic-building");

    if (progress >= 65 && logoShell && !logoShell.classList.contains("magic-logo-revealed")) {
      logoShell.classList.add("magic-logo-revealed");
      energy?.classList.add("magic-energy-active");
      mascot?.classList.add("magic-creating");
      sparks.forEach((spark, index) => {
        window.setTimeout(() => {
          spark.classList.remove("spark-active");
          void spark.offsetWidth;
          spark.classList.add("spark-active");
        }, index * 140);
      });
    }

    if (progress >= 88) {
      loader.classList.add("magic-reveal");
    }
  }

  function finishLoader() {
    if (finished) return;
    finished = true;

    if (animationFrame !== null) {
      cancelAnimationFrame(animationFrame);
    }

    setProgress(100);
    loader.classList.add("magic-complete");

    window.setTimeout(() => {
      loader.classList.add("magic-loader-exit");
      loader.setAttribute("aria-hidden", "true");

      window.setTimeout(() => {
        loader.remove();
      }, 900);
    }, 500);
  }

  function animate(time) {
    if (finished) return;

    if (!lastTime) lastTime = time;

    const delta = Math.min(time - lastTime, 50);
    lastTime = time;

    // Le pourcentage représente l'animation de construction,
    // et non une mesure exacte du téléchargement du site.
    if (progress < 65) {
      setProgress(progress + delta * 0.018);
    } else if (progress < 88) {
      setProgress(progress + delta * 0.009);
    } else if (pageReady) {
      setProgress(progress + delta * 0.045);
    }

    if (pageReady && progress >= 100) {
      finishLoader();
      return;
    }

    animationFrame = requestAnimationFrame(animate);
  }

  function begin() {
    if (animationFrame === null && !finished) {
      animationFrame = requestAnimationFrame(animate);
    }
  }

  // Attendre les ressources de la page avant de terminer.
  if (!pageReady) {
    window.addEventListener("load", () => {
      pageReady = true;
    }, { once: true });
  }

  // Ne jamais laisser l'écran masquer le site indéfiniment.
  const safetyTimeout = window.setTimeout(() => {
    pageReady = true;
    setProgress(100);
    finishLoader();
  }, 9000);

  // Si le logo est introuvable, la construction reste visuelle
  // et le site continue à fonctionner normalement.
  if (logo) {
    logo.addEventListener("error", () => {
      console.error(
        "EBOU : logo introuvable. Vérifie le chemin /assets/app-icon.jpeg."
      );
    }, { once: true });
  }

  // Déclenchement de petites étincelles pendant la construction.
  const sparkleInterval = window.setInterval(() => {
    if (finished) {
      window.clearInterval(sparkleInterval);
      window.clearTimeout(safetyTimeout);
      return;
    }

    const spark = sparks[Math.floor(Math.random() * sparks.length)];

    if (spark) {
      spark.classList.remove("spark-active");
      void spark.offsetWidth;
      spark.classList.add("spark-active");
    }
  }, 700);

  begin();
})();
