// ========================================

const select = document.getElementById("languageSelect");

const languageFlags = {
  fr: { flag: "🇫🇷", code: "FR" },
  en: { flag: "🇬🇧", code: "EN" },
  ee: { flag: "🇹🇬", code: "EE" }
};

function updateLanguageSwitcher(lang) {
  const settings = languageFlags[lang] || languageFlags.fr;
  const flag = document.getElementById("languageFlag");
  const code = document.getElementById("languageCode");

  if (flag) flag.textContent = settings.flag;
  if (code) code.textContent = settings.code;
}

function setLanguage(lang) {
  const selectedLang = translations[lang] ? lang : "fr";
  const dict = translations[selectedLang];

  document.documentElement.lang = selectedLang;

  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.dataset.i18n;
    const value = dict[key];

    if (value !== undefined) {
      el.innerHTML = value;
    }
  });

  if (select) select.value = selectedLang;

  updateLanguageSwitcher(selectedLang);

  try {
    localStorage.setItem("ebou-language", selectedLang);
  } catch (error) {
    // Le site continue de fonctionner si le stockage est indisponible.
  }
}

let initialLang = "fr";

try {
  const savedLang = localStorage.getItem("ebou-language");
  if (savedLang && translations[savedLang]) {
    initialLang = savedLang;
  }
} catch (error) {
  // Le français reste la langue par défaut.
}

setLanguage(initialLang);

select?.addEventListener("change", (event) => {
  setLanguage(event.target.value);
});

